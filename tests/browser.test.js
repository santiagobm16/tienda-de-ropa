import { resolve } from 'node:path'
import { chromium } from 'playwright'
import { preview } from 'vite'
import { variantKey } from '../src/data/demo.js'
import { STORE_KEY, SESSION_KEY } from '../src/services/store.js'

let base = process.env.URBAN_TEST_URL
const demoImage = resolve('public/images/camisetas.webp')
const extraImage = resolve('public/images/chaquetas.webp')
const adminPaths = ['/admin', '/admin/productos', '/admin/productos/nuevo',
  '/admin/productos/editar/camisetas-1', '/admin/categorias', '/admin/inventario', '/admin/pedidos']
const visible = locator => locator.waitFor({ state: 'visible', timeout: 6500 })
const gone = locator => locator.waitFor({ state: 'hidden', timeout: 6500 })
const button = (page, name) => page.getByRole('button', { name, exact: true })
const link = (page, name) => page.getByRole('link', { name, exact: true })
const heading = (page, name) => page.getByRole('heading', { name, exact: true })
const field = (page, name) => page.getByLabel(name, { exact: true })
const data = page => page.evaluate(key => JSON.parse(localStorage.getItem(key)), STORE_KEY)
const go = async (page, path) => { assert.equal((await page.goto(base + path)).status(), 200) }
const stockOf = async (page, id, size, color) => (await data(page)).products.find(product => product.id === id).inventory[variantKey(size, color)]
const screenshot = (page, name) => process.env.URBAN_TEST_SCREENSHOTS
  ? page.screenshot({ path: resolve(process.env.URBAN_TEST_SCREENSHOTS, name + '.png'), fullPage: false, animations: 'disabled' }) : null

async function login(page, account, password) {
  await field(page, 'Correo electrónico').fill(account + '@urbanmen.com')
  await field(page, 'Contraseña').fill(password)
  await button(page, 'Iniciar sesión').click()
}

async function logout(page) {
  await button(page, 'Menú de usuario').click()
  await button(page, 'Cerrar sesión').click()
  await page.waitForURL(base + '/')
}

